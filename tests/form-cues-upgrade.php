<?php
use TF\Auth;
use TF\Catalog;
use TF\Migrator;
// Included by run.php: exercise a deployed database upgrade, not just fresh seeds.
$cueDb = $freshDb('cues');
Migrator::ensure($cueDb, 33);
$cueOwner = (new Auth($cueDb, []))->createUser('cue-owner', 'test-password');
$cueOriginal = $cueDb->one("SELECT * FROM exercises WHERE slug='dumbbell-curl' AND user_id IS NULL");
$cueId = (int) $cueOriginal['id'];
$cueDb->run('UPDATE exercises SET cues=?, archived=1 WHERE id=?', ['Start with your palm facing your thigh and turn it up as you curl. Do both sides. Keep your upper arms still and lower all the way down.', $cueId]);
$cueCustom = $cueOriginal;
unset($cueCustom['id']);
$cueCustom['user_id'] = $cueOwner;
$cueCustom['cues'] = 'My personal curl instructions.';
$cueCustomId = $cueDb->insert('exercises', $cueCustom);
$cueCustomBefore = $cueDb->one('SELECT * FROM exercises WHERE id=?', [$cueCustomId]);
$cueDb->run("UPDATE exercises SET cues='Locally edited hammer instructions.' WHERE slug='hammer-curl' AND user_id IS NULL");
$cueDb->insert('exercise_notes', ['user_id' => $cueOwner, 'variant_key' => (string) $cueId, 'note' => 'Keep my seat setting.', 'updated_at' => '2026-01-01 00:00:00']);
$cueDb->insert('workouts', ['id' => uuid(), 'user_id' => $cueOwner, 'gym_id' => null, 'gym_name' => 'Test gym', 'day_type' => 'full', 'status' => 'done', 'unit' => 'lb', 'started_at' => '2026-01-01 10:00:00', 'completed_at' => '2026-01-01 10:30:00', 'notes' => 'Keep my workout.', 'rev' => 2, 'updated_at' => '2026-01-01 10:30:00']);
$cueBeforeRows = $cueDb->all('SELECT * FROM exercises ORDER BY id');
$cueBeforeNotes = $cueDb->all('SELECT * FROM exercise_notes');
$cueBeforeWorkouts = $cueDb->all('SELECT * FROM workouts');
$cueMigration = require dirname(__DIR__) . '/web/private/migrations/034_clarify_form_cues.php';
$cueMigration($cueDb, new Migrator($cueDb));
$cueAfterRows = $cueDb->all('SELECT * FROM exercises ORDER BY id');
$cueExpected = array_values(array_filter(Catalog::exercises(), static fn($e) => $e[0] === 'dumbbell-curl'))[0][8];
check('cue upgrade replaces a previous default without changing its ID', $cueDb->val('SELECT cues FROM exercises WHERE id=?', [$cueId]) === $cueExpected);
check('cue upgrade preserves personal exercises even with a built-in slug', $cueDb->one('SELECT * FROM exercises WHERE id=?', [$cueCustomId]) === $cueCustomBefore);
check('cue upgrade preserves locally customized built-in cues', $cueDb->val("SELECT cues FROM exercises WHERE slug='hammer-curl' AND user_id IS NULL") === 'Locally edited hammer instructions.');
$cueStrip = static function ($rows) { return array_map(static function ($row) { unset($row['cues']); return $row; }, $rows); };
check('cue upgrade changes no exercise metadata or row counts', $cueStrip($cueBeforeRows) === $cueStrip($cueAfterRows));
check('cue upgrade preserves notes and workout records', $cueBeforeNotes === $cueDb->all('SELECT * FROM exercise_notes') && $cueBeforeWorkouts === $cueDb->all('SELECT * FROM workouts'));
$cueMigration($cueDb, new Migrator($cueDb));
check('cue migration can run again without changing anything', $cueAfterRows === $cueDb->all('SELECT * FROM exercises ORDER BY id'));
unset($cueDb);
@unlink("$file-cues");
@unlink("$file-cues-wal");
@unlink("$file-cues-shm");
